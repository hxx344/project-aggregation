// Run with playwright-cli run-code --filename against a production preview on port 4177.
async (page) => {
  const origin = 'http://127.0.0.1:4177';
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => { window.EventSource = class { close() {} }; });
  await page.route(`${origin}/api/**`, async route => {
    const path = new URL(route.request().url()).pathname;
    const send = (body, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });
    if (path === '/api/session') return send({ authenticated: true, csrfToken: 'fixture' });
    if (path === '/api/health') return send({ status: 'ok' });
    if (path === '/api/overview') return send({ generatedAt: new Date().toISOString(), projects: [] });
    if (path === '/api/system/updates') return send({ enabled: false, checking: false, modules: [] });
    return send({ ok: true }, path === '/api/diagnostic-failure' ? 503 : 200);
  });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(origin);
  await page.getByRole('button', { name: '请求诊断', exact: true }).click();
  await page.getByRole('heading', { name: '请求诊断', exact: true }).waitFor();
  await page.evaluate(() => { window.__diagnosticOriginal = window.fetch; });
  await page.getByRole('button', { name: '开始监控', exact: true }).click();
  await page.evaluate(async () => { await fetch('/api/diagnostic-start').then(response => response.json()); });
  await page.locator('.diagnostic-logs').getByText('/api/diagnostic-start', { exact: true }).waitFor();
  await page.getByRole('button', { name: '总览', exact: true }).click();
  assert(!await page.getByRole('button', { name: '停止监控', exact: true }).isVisible(), 'diagnostic controls are hidden off-page');
  await page.evaluate(async () => { await fetch('/api/diagnostic-away'); await fetch('/api/diagnostic-failure'); });
  await page.getByRole('button', { name: '请求诊断', exact: true }).click();
  await page.locator('.diagnostic-logs').getByText('/api/diagnostic-away', { exact: true }).waitFor();
  assert(await page.locator('.diagnostic-logs').getByText('/api/diagnostic-start', { exact: true }).count() === 1, 'earlier records survive navigation');
  assert(await page.locator('.diagnostic-logs tr.error-row').count() === 1, 'HTTP failures are recorded');
  await page.getByRole('button', { name: '停止监控', exact: true }).click();
  assert(await page.evaluate(() => window.fetch === window.__diagnosticOriginal), 'stopping restores fetch');
  await page.evaluate(async () => { await fetch('/api/diagnostic-stopped'); });
  assert(await page.locator('.diagnostic-logs').getByText('/api/diagnostic-stopped', { exact: true }).count() === 0, 'stopping ends capture');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出数据', exact: true }).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream();
  let content = '';
  for await (const chunk of stream) content += chunk.toString();
  const exported = JSON.parse(content);
  assert(exported.logs.some(log => log.url === '/api/diagnostic-away'), 'export includes requests from another page');
  assert(exported.measurement.duration.includes('response headers'), 'export states the measurement boundary');
  await page.screenshot({ path: 'output/playwright/request-diagnostics-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'diagnostic tables do not overflow the mobile viewport');
  await page.screenshot({ path: 'output/playwright/request-diagnostics-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '清空记录', exact: true }).click();
  assert(await page.getByRole('button', { name: '导出数据', exact: true }).isDisabled(), 'clear removes captured data');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${origin}/?view=diagnostic`);
  await page.getByRole('button', { name: '开始监控', exact: true }).waitFor();
  await page.evaluate(() => { window.__diagnosticOriginal = window.fetch; });
  await page.getByRole('button', { name: '开始监控', exact: true }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.getByRole('heading', { name: '进入工作台' }).waitFor();
  assert(await page.evaluate(() => window.fetch === window.__diagnosticOriginal), 'logout cleans up the observer');
  assert(errors.length === 0, errors.join('\n'));
  console.log(JSON.stringify({ passed: true, scenarios: ['navigation', 'cross-page capture', 'HTTP failure', 'stop', 'export', 'mobile layout', 'clear', 'direct URL', 'logout cleanup'] }));
}
